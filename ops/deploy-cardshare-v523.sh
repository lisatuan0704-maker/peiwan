# 小小酒館：闆卡分享（api.tinytavern.tw/v1/card-share）v523
# 1. 「一起入鏡」：老闆可以從自己擁有的寵物（雪球／鈴／啵幽／水晶龍／甜甜犬）、座椅（我生日推車／蘋果傳說的鏡子）各挑一個進闆卡圖；
#    擁有與否照 peiwan/owned 再確認一次，座椅用網站同一支 js/tt-seats.js 畫（跟大廳一樣），預覽看到的就是發出去的那張。
# 2. 畫卡用的 Chromium 當掉／沒開起來時，下一張自動重開（以前會一直回「分享功能暫時休息中」直到服務重啟）。
# 3. 沒有代碼的錯誤會在服務紀錄留一行 CARD_SHARE_UNEXPECTED <原因>（只有錯誤名稱，不含登入憑證或客人資料）。
# 4. 容器記憶體上限 512m → 768m（11/11 檢查：服務本身＋畫卡用的 Chromium 擠爆 512m 被系統強制結束過）。
# 試畫一律在另開的測試容器裡跑（同樣的安全設定與記憶體上限），不擠正在服務的那個容器。
# 只換 core／http／live-profiles／renderer 四個檔，新增 assets/pets、assets/seats；先核對主機上是預期的版本，不一樣就停止、什麼都不動。
# 新版本先跑測試與試畫（假角色，不讀真資料、不發 Discord）才換上；換上後健康檢查或試畫失敗會自動還原舊版。
# 在主機的 root 終端機執行。
set -euo pipefail
R="${TT_ROOT:-}"
TAG=20261111-v523
UNIT=$R/etc/systemd/system/tinytavern-card-share.service
DST=$R/opt/tinytavern/releases/card-share-$TAG
say(){ printf '\n== %s\n' "$*"; }
CUR=$(grep -o 'tinytavern-card-share:[A-Za-z0-9._-]*' "$UNIT" | head -1 | cut -d: -f2)
say "目前版本：$CUR"
[ -n "$CUR" ] || { echo "找不到目前版本，停止。"; exit 1; }
if [ "$CUR" = "$TAG" ]; then echo "已經是 $TAG，不用再部署。"; exit 0; fi
[ "$(grep -cF "tinytavern-card-share:$CUR" "$UNIT")" = 1 ] || { echo "服務設定裡的版本字樣不只一處，為了安全停止。"; exit 1; }
[ ! -e "$DST" ] || { echo "$DST 已經存在（可能部署到一半），請先看一下再刪掉重跑。停止。"; exit 1; }

say "核對主機上要換掉的檔案是預期版本"
declare -A WANT=([core.cjs]=646cdd092db6b8f872ee3270c3d129b4afb8ad68bbb37ed4db22162d070e43e6 [http.cjs]=ba75df8e08b120c5e4c497f236d3aee7bda914111ae60c0c30691d18f6a4932c [live-profiles.cjs]=22be66886ce223fdae16b38f4d2a52a31187349a3b1d675b87cddee583e44457 [renderer.cjs]=96d51d85dacc7e6eacfb23a13cab075947898455ec127068e1c986cdd69656ef)
for f in core.cjs http.cjs live-profiles.cjs renderer.cjs; do
  h=$(docker run --rm --entrypoint sha256sum "tinytavern-card-share:$CUR" "/card-share/$f" | cut -d' ' -f1)
  [ "$h" = "${WANT[$f]}" ] || { echo "$f 跟預期版本不同（$h），主機上的程式可能被改過，停止，沒有任何變動。"; exit 1; }
done
echo "四個檔都是預期版本"

say "準備新版本 $TAG"
mkdir -p "$DST"
base64 -d > "$DST/p.tgz" <<'B64'
