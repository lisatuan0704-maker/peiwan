#    按了就開語音房；3 分鐘沒選＝私人房。之後老闆隨時可在聊天室按按鈕切換、邀朋友／請朋友離開（兩間房一起），
#    語音房另外給老闆「管理頻道」（改房名、人數上限；權限設定仍由 TT 管，老闆不能把冒險者或 TT 請出去）。語音房收起來時聊天室一起收。
