# service-server.cjs 只多兩處（啟動設定、按鈕入口最前面）。順便補檢查 v511 語音登記名字備援（已經有就跳過）。
# 在主機的 root 終端機執行。任何一步失敗都會停止；健康檢查失敗會自動還原舊版。
set -euo pipefail
R="${TT_ROOT:-}"
