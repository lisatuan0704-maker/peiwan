#    新委託私訊都改給小帳；沒填、或小帳不在伺服器裡，照舊用手冊綁的帳號。
# 3. D：「時間到不應該消失，全部離開才消失」→ 正常結束（冒險者按結束、或時間到）不再收回房間權限，房裡的人可以繼續、斷線也能回來，
#    大家都離開 30 秒後才刪房（聊天室一起刪）。只有取消／退款的單照舊馬上收起來。
# 4. 老闆點單時填的「想玩什麼」（clientOrders/<單>/game，網站 v514 新欄位）：新委託私訊和專屬聊天室開場訊息多一行「想玩：…」（沒填就沒有）。
