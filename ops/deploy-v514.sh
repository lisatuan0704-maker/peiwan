same staff-order-dm.cjs ba678bfb482a6749f188f2e87609e28806686d02ae6708eb1a52c207cb10b405 9a242f8ca2c55030a0b41c7ca6d1559b2f357670c41c46e71b5794087804eb28 || { echo "staff-order-dm.cjs 跟預期版本不同（$(sha256sum "$SRC/order-voice-bot/staff-order-dm.cjs" | cut -c1-16)），為了安全停止，沒有任何變動。請把這行拍給 Claude。"; exit 1; }
echo "voice.cjs、staff-order-dm.cjs 都是預期版本"
say "建立新版本 $TAG"
cp -a "$SRC" "$DST"
